# --- kubernetes -----------------------------------------------------------

_TRANSPORTS = {"http": _K8sHttpTransport, "library": _K8sLibraryTransport}


def _kubeconfig_path():
    _need(
        os.environ.get("CRONSTABLE_LIVE_K8S") == "1",
        "CRONSTABLE_LIVE_K8S is not 1: no live apiserver to test against",
    )
    first = os.environ.get("KUBECONFIG", "").split(os.pathsep)[0]
    path = first or os.path.join(os.path.expanduser("~"), ".kube", "config")
    _need(os.path.exists(path), "no kubeconfig at " + path)
    return path


def _need_transport(kind):
    if kind == "library":
        _need(
            importlib.util.find_spec("kubernetes") is not None,
            "the kubernetes package is not installed: the library transport "
            "cannot run live",
        )


def _k8s_backend(
    lease, kind, *, node="node-a", duration=15, renew=10, retry=2
):
    namespace = os.environ.get("CRONSTABLE_LIVE_K8S_NAMESPACE", "default")
    yaml = (
        "cluster:\n"
        "  backend: kubernetes\n"
        "  nodeName: " + node + "\n"
        "  connectTimeout: 5\n"
        "  kubernetes:\n"
        "    leaseName: " + lease + "\n"
        "    leaseNamespace: " + namespace + "\n"
        "    clientLibrary: " + kind + "\n"
        "    kubeconfig: '" + _kubeconfig_path().replace("\\", "/") + "'\n"
        "    leaseDurationSeconds: " + str(duration) + "\n"
        "    renewDeadlineSeconds: " + str(renew) + "\n"
        "    retryPeriodSeconds: " + str(retry) + "\n"
    )
    cfg = parse_config_string(yaml, "").cluster_config
    return KubernetesBackend(cfg, lambda: "v1:live")


@contextlib.asynccontextmanager
async def _raw_apiserver(lease):
    """``call(method, path, body)`` with the HTTP transport's credentials."""
    transport = _K8sHttpTransport(_k8s_backend(lease, "http"))
    await transport.setup()

    async def call(method, path, body):
        async with transport._session.request(
            method,
            transport._base_url + path,
            json=body,
            ssl=transport._ssl,
            headers=transport._auth_headers(),
        ) as resp:
            return resp.status, await resp.json()

    try:
        yield transport, call
    finally:
        await transport.close()


@contextlib.asynccontextmanager
async def _k8s_nodes(test, kinds, **timing):
    """One backend per entry of ``kinds`` on a run-unique Lease."""
    for kind in kinds:
        _need_transport(kind)
    lease = "cronstable-live-{}-{}".format(_RUN, test)
    nodes = [
        _k8s_backend(lease, kind, node="node-" + "abcdef"[i], **timing)
        for i, kind in enumerate(kinds)
    ]
    try:
        yield nodes
    finally:
        for node in nodes:
            await node.stop()
        async with _raw_apiserver(lease) as (transport, call):
            path = transport._lease_url()[len(transport._base_url) :]
            await call("DELETE", path, None)


async def _k8s_stored(lease):
    async with _raw_apiserver(lease) as (transport, _call):
        return await transport.observe()


async def test_live_apiserver_lease_api_matches_the_fake():
    namespace = os.environ.get("CRONSTABLE_LIVE_K8S_NAMESPACE", "default")
    name = "cronstable-live-{}-conformance".format(_RUN)
    async with _raw_apiserver(name) as (_transport, call):
        await check_lease_api(call, namespace, name)


@pytest.mark.parametrize("kind", ["http", "library"])
async def test_live_k8s_acquire_renew_release(kind):
    async with _k8s_nodes("acquire-" + kind, [kind]) as [a]:
        await a.start()
        assert type(a._transport) is _TRANSPORTS[kind]
        assert a.is_leader() and a.is_quorate()
        stored = await _k8s_stored(a.lease_name)
        assert stored["spec"]["holderIdentity"] == a.identity
        version = stored["metadata"]["resourceVersion"]
        for _ in range(3):
            await a._renew_once()
            assert a.is_leader()
        assert (await _k8s_stored(a.lease_name))["metadata"][
            "resourceVersion"
        ] != version
        await a.mark_reboot_ran("oneshot")
        await a.stop()
        # handed back: no holder, and the @reboot-ran annotation kept
        released = await _k8s_stored(a.lease_name)
        assert not released["spec"].get("holderIdentity")
        assert REBOOT_RAN_KEY in released["metadata"]["annotations"]


@pytest.mark.parametrize(
    "kinds",
    [("http", "http"), ("library", "library"), ("library", "http")],
    ids=["http", "library", "mixed"],
)
async def test_live_k8s_two_nodes_elect_one_leader_and_hand_over(kinds):
    async with _k8s_nodes("contention-" + "-".join(kinds), kinds) as [a, b]:
        await a.start()
        await b.start()
        assert a.is_leader() and not b.is_leader()
        assert a.leader_name() == b.leader_name() == "node-a"
        for _ in range(3):
            await b._renew_once()
            await a._renew_once()
            assert [a.is_leader(), b.is_leader()] == [True, False]
        await a.mark_reboot_ran("oneshot")
        await a.stop()
        await b._renew_once()
        assert b.is_leader() and b.leader_name() == "node-b"
        assert b.reboot_ran("oneshot") is True
        stored = await _k8s_stored(b.lease_name)
        assert stored["spec"]["holderIdentity"] == b.identity
        assert stored["spec"]["leaseTransitions"] == 1



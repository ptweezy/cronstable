"""One frozen X-Wing vector, replayed here and in the companion app.

``tests/test_push.py`` proves this daemon opens what this daemon sealed,
and the app's ``SealedBoxTests`` proves the same of CryptoKit.  Two
self-consistent implementations agree with themselves while drifting
apart from each other: a ``cryptography`` or CryptoKit release that
reordered a public key's halves, changed the X-Wing seed expansion or
reframed the wire blob would break every production alert and leave both
suites green.  This module and
``Packages/CronstableKit/Tests/CronstableKitTests/XWingVectorTests.swift``
(cronstable-ios) close that gap by replaying one fixture that neither
side generates.

The fixture is the production direction end to end: the daemon seals, the
app opens.  It holds a 32-byte X-Wing seed, the 1216-byte public key both
libraries derive from it, an alert plaintext, and that plaintext sealed to
that key by :func:`cronstable.push.seal_to_device`.  Each side derives the
keypair from the seed, asserts the derived public key is the frozen one
byte for byte, and opens the frozen blob.  A library that moves under
either side fails there while the other holds, and a suite that only
replays its own output cannot show that.

The seed is the app's own stable private form.  CryptoKit's
``XWingMLKEM768X25519.PrivateKey`` exposes ``seedRepresentation`` and takes
it back through ``init(seedRepresentation:publicKey:)``, and ``DeviceKey``
stores exactly those 32 bytes in the keychain.  ``cryptography`` has no
X-Wing composite keygen, so :func:`_private_key` expands the seed the way
draft-connolly-cfrg-xwing-kem specifies; that expansion is itself part of
what the vector pins.

Provenance: generated by ``tests/gen_push_vectors.py`` against
cryptography 50.0.1 (CPython 3.13, macOS 27 arm64), and verified to open
under CryptoKit in Xcode 27.0 (27A5252f, Swift 6.4).  Regenerate with
``python tests/gen_push_vectors.py``, which prints both suites' constant
blocks.

The ``requires_xwing`` guard is the shared one in ``tests/_helpers.py``,
the same marker ``tests/test_push.py`` rides on: cryptography is a dev
dependency with wheels on every CI cell but win-arm64, and only the
tests that touch key material stand down without it.  Never make this
a module-level ``importorskip``; that once vaporized the whole push suite
on cells that had the wheel.
"""


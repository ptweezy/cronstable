"""In-house cron expression engine.

:class:`CronTab` answers :meth:`CronTab.next` (when does this fire
next?), :meth:`CronTab.test` (does this instant match?),
:meth:`CronTab.prev` and :meth:`CronTab.occurrences`, plus read-only
properties exposing the parsed field sets.  Behavior is pinned by golden
vectors in ``tests/data/cron_golden.json`` (regenerated by
``tests/gen_cron_golden.py``, replayed by ``tests/test_cronexpr.py``);
its ``"extension": true`` entries pin the L-/W/# extensions.

The dialect (the "Schedules and Timezones" wiki page is the user docs):

- 5 fields ``minute hour dayOfMonth month dayOfWeek`` (implicit second 0,
  any year); 6 adds a trailing ``year``; 7 adds a leading ``second``.
- Values, lists, ranges, steps (``*/5``, ``1-9/2``; ``5/15`` runs to the
  field's end), case-insensitive month/weekday names.
- Weekdays 0-7, BOTH 0 and 7 Sunday; a range ending in 0 wraps its end to
  7 (``sat-sun``, ``6-0``); star/step expansion runs 0-6.
- ``L`` alone in day-of-month: the month's last day.  ``L<n>`` or
  ``L<a>-<b>`` in day-of-week: the month's LAST such weekday (``L5`` =
  last Friday).  No other field takes an ``L``.
- Extensions (each a parse error in the legacy dialect, so no old
  schedule changed meaning): day-of-month ``L-<n>`` (n days before the
  final day, n 1-30), ``<n>W`` (weekday Mon-Fri nearest day n, flipped
  inward at month edges, no fire when the month lacks day n), ``LW``
  (last weekday); day-of-week ``<d>#<n>`` (n-th such weekday, n 1-5, no
  fire when absent).  All are ordinary list items under the AND rule.
- ``@yearly``/``@annually``/``@monthly``/``@weekly``/``@daily``/``@hourly``
  expand to five-field forms; ``@reboot`` never reaches this parser;
  ``@midnight`` becomes ``@daily`` in the classic-crontab loader.
- ``?`` alone in either day field reads as ``*`` (Quartz); anywhere else
  an error, and Quartz-smelling parse errors carry a dialect hint.
- ``H`` (Jenkins-style, any field but year): a value hashed from the
  ``hash_key`` (the job name), salted per field, stable across restarts
  and hosts, so fleets spread while each job keeps ONE predictable slot.
  Forms ``H``, ``H(a-b)``, ``H/n``, ``H(a-b)/n``; rangeless day-of-month
  forms hash over 1-28.  No ``hash_key`` rejects ``H``;
  :attr:`CronTab.resolved_source` shows the hashed values.
- Restricted day-of-month AND day-of-week must BOTH match (``0 0 13 * 5``
  = Friday the 13th); Vixie cron fires on either.
- ``year`` accepts 1970-2099; :meth:`CronTab.test` does not bound an
  unrestricted year, but :meth:`CronTab.next` stops at 2099 and returns
  ``None`` when no occurrence remains.

Time model: ``next`` is strictly future (a matching "now" yields the
following occurrence) and runs in ``now``'s civil clock; an aware match
resolves in its zone (``fold=0``) and the delay is true elapsed seconds
across offset changes: a spring-forward gap label fires once at its
shifted time, an ambiguous fall-back wall time on its first occurrence
only.  ``LOCAL_ZONE`` is the host's local clock as a tzinfo, so a
local-clock schedule takes that same aware path under the host's DST
rules.  ``test`` reads civil fields, ignoring microseconds.  ``prev``
mirrors into the past (floor 1970); ``occurrences`` iterates real
instants, never yielding one twice.
"""


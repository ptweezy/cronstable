INFO = b"cronstable-push-xwing"

#: Where the wire blob splits, and what sealing costs.  Duplicated from
#: docs/relay-protocol.md for the same reason as ``INFO``.
ENC_BYTES = 1120
OVERHEAD_BYTES = 1136
PUBLIC_KEY_BYTES = 1216


def _expand_seed(seed: bytes) -> tuple[bytes, bytes]:
    """An X-Wing seed split into its two private halves.

    draft-connolly-cfrg-xwing-kem's ``expandDecapsulationKey``: 96 bytes
    of SHAKE256 over the seed, read as the ML-KEM-768 d||z seed (which
    ``MLKEM768PrivateKey.from_seed_bytes`` takes, and which
    ``private_bytes_raw`` returns) followed by the X25519 private key.
    CryptoKit does this inside ``init(seedRepresentation:publicKey:)``;
    nothing in cryptography exposes it, so both halves of the vector
    ride on the two libraries expanding a seed identically.
    """
    expanded = hashlib.shake_256(seed).digest(96)
    return expanded[0:64], expanded[64:96]


def _private_key(seed: bytes):
    """The hybrid private key for ``seed``, and its 1216-byte wire key."""
    from cryptography.hazmat.primitives import hpke
    from cryptography.hazmat.primitives.asymmetric import mlkem, x25519

    mlkem_seed, x25519_seed = _expand_seed(seed)
    mlkem_private = mlkem.MLKEM768PrivateKey.from_seed_bytes(mlkem_seed)
    x_private = x25519.X25519PrivateKey.from_private_bytes(x25519_seed)
    wire = (
        mlkem_private.public_key().public_bytes_raw()
        + x_private.public_key().public_bytes_raw()
    )
    return hpke.MLKEM768X25519PrivateKey(mlkem_private, x_private), wire


def _open(sealed: bytes, private) -> bytes:
    """Open one X-Wing blob the way the app does: single-shot HPKE
    decrypt over the whole ``enc||ct`` wire form."""
    from cryptography.hazmat.primitives.hpke import AEAD, KDF, KEM, Suite

    suite = Suite(KEM.MLKEM768_X25519, KDF.HKDF_SHA256, AEAD.AES_256_GCM)
    return suite.decrypt(sealed, private, info=INFO)


# ------------------------------------------------------------- the tests


def test_the_vector_matches_the_daemons_own_suite_table():
    # The fixture's widths are quoted as literals above so the vector
    # stands alone; this ties those literals back to the table the rest
    # of the daemon sizes and validates against, so a table edit cannot
    # leave the vector describing a wire nobody speaks.
    spec = push.SUITES[push.SUITE_XWING]
    assert spec.public_key_bytes == PUBLIC_KEY_BYTES
    assert spec.overhead == OVERHEAD_BYTES
    assert len(base64.b64decode(PUBLIC_KEY_B64)) == PUBLIC_KEY_BYTES
    assert len(base64.b64decode(CIPHERTEXT_B64)) == (
        len(PLAINTEXT) + OVERHEAD_BYTES
    )


@requires_xwing
def test_the_frozen_seed_derives_the_frozen_public_key():
    # The cross-implementation pin on key derivation. CryptoKit expands
    # the same 32 bytes inside init(seedRepresentation:publicKey:) and
    # the Swift suite asserts the same equality against the same
    # constant, so a seed expansion, an ML-KEM keygen or a half-order
    # that moves under either library fails on one side.
    _, wire = _private_key(base64.b64decode(SEED_B64))
    assert base64.b64encode(wire).decode("ascii") == PUBLIC_KEY_B64
    # Named explicitly: the halves are ordered ML-KEM first, and the
    # ordering is the kind of thing a library release flips.
    assert len(wire[:1184]) == 1184
    assert len(wire[1184:]) == 32


@requires_xwing
def test_sealing_to_the_frozen_key_frames_the_documented_widths():
    # Framing is the other half of the contract the app's split depends
    # on: the app slices the first 1120 bytes off as the encapsulated
    # key and hands the rest to the AEAD, so enc width and total
    # overhead are wire, not an implementation detail.
    from cryptography.hazmat.primitives.hpke import KEM

    assert KEM.MLKEM768_X25519.enc_length() == ENC_BYTES
    sealed = base64.b64decode(
        push.seal_to_device(PUBLIC_KEY_B64, PLAINTEXT, push.SUITE_XWING)
    )
    assert len(sealed) == len(PLAINTEXT) + OVERHEAD_BYTES
    # enc, then the ciphertext and its 16-byte GCM tag.
    assert len(sealed) - ENC_BYTES == len(PLAINTEXT) + 16


@requires_xwing
def test_the_frozen_blob_opens_to_the_frozen_plaintext():
    # The vector replayed: bytes sealed under the library version named
    # in the module docstring open with the key the frozen seed rebuilds.
    # The Swift suite opens these exact bytes through CryptoKit.
    private, _ = _private_key(base64.b64decode(SEED_B64))
    opened = _open(base64.b64decode(CIPHERTEXT_B64), private)
    assert opened == PLAINTEXT
    # Shaped like a real alert, so the vector exercises a payload the app
    # actually renders rather than a token string.
    assert json.loads(opened.decode("utf-8"))["name"] == "nightly-backup"


@requires_xwing
def test_the_frozen_blob_stays_shut_under_a_different_info_string():
    # The info bytes are half the binding both sides commit to; a
    # daemon that changed them would seal blobs the app cannot open, and
    # the failure would look like a key problem. Pin it here.
    from cryptography.exceptions import InvalidTag
    from cryptography.hazmat.primitives.hpke import AEAD, KDF, KEM, Suite

    private, _ = _private_key(base64.b64decode(SEED_B64))
    suite = Suite(KEM.MLKEM768_X25519, KDF.HKDF_SHA256, AEAD.AES_256_GCM)
    with pytest.raises(InvalidTag):
        suite.decrypt(
            base64.b64decode(CIPHERTEXT_B64),
            private,
            info=b"cronstable-push-xwing ",
        )


@requires_xwing
def test_the_frozen_blob_stays_shut_under_a_different_seed():
    # One flipped seed bit is a different key pair, which is the property
    # the whole pairing model rests on.
    from cryptography.exceptions import InvalidTag

    seed = bytearray(base64.b64decode(SEED_B64))
    seed[0] ^= 0x01
    other, other_wire = _private_key(bytes(seed))
    assert base64.b64encode(other_wire).decode("ascii") != PUBLIC_KEY_B64
    with pytest.raises(InvalidTag):
        _open(base64.b64decode(CIPHERTEXT_B64), other)

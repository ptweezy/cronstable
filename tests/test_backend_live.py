@pytest.mark.parametrize("kind", ["http", "library"])
async def test_live_k8s_leadership_moves_when_the_holder_stops_renewing(kind):
    timing = {"duration": 4, "renew": 2, "retry": 1}
    async with _k8s_nodes("expiry-" + kind, [kind] * 2, **timing) as [a, b]:
        await a.start()
        await b.start()
        assert a.is_leader() and not b.is_leader()
        # the holder dies without releasing: its renew loop simply stops
        a._task.cancel()
        with contextlib.suppress(asyncio.CancelledError):
            await a._task
        a._task = None
        # the follower's own renew loop takes the lease over
        await _poll(b.is_leader)
        assert not a.is_leader()
        await a._renew_once()
        assert not a.is_leader()
        assert a.leader_name() == "node-b"

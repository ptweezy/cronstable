#: next() never searches past this year: the year column's maximum, and the
#: horizon that makes a never-occurring schedule (Feb 30) come back as
#: ``None`` instead of looping forever.
_YEAR_HORIZON = 2099

#: prev() never searches before this year: the year column's minimum, the
#: backward mirror of ``_YEAR_HORIZON``.
_YEAR_FLOOR = 1970

#: The first instant past the horizon, which prev() clamps a far-future
#: ``now`` to (see there).
_HORIZON_EDGE = datetime.datetime(_YEAR_HORIZON + 1, 1, 1)

#: How far back :meth:`CronTab._gap_rewound_seed` probes for a spring-forward.
